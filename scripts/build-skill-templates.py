#!/usr/bin/env python3
"""
scripts/build-skill-templates.py

Regenerates src/shared/skill/templates.ts from the markdown source files
in static/skill-template/. Run this after editing any of:
  - static/skill-template/QA-REPORT-SKILL.md
  - static/skill-template/playbooks/report.md
  - static/skill-template/README.md

Usage:
    python3 scripts/build-skill-templates.py
"""

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SKILL_MD_PATH    = os.path.join(ROOT, 'static', 'skill-template', 'QA-REPORT-SKILL.md')
PLAYBOOK_MD_PATH = os.path.join(ROOT, 'static', 'skill-template', 'playbooks', 'report.md')
README_MD_PATH   = os.path.join(ROOT, 'static', 'skill-template', 'README.md')
OUTPUT_PATH      = os.path.join(ROOT, 'src', 'shared', 'skill', 'templates.ts')


def read(path: str) -> str:
    with open(path, 'r', encoding='utf-8') as f:
        return f.read()


def main() -> None:
    skill_md    = read(SKILL_MD_PATH)
    playbook_md = read(PLAYBOOK_MD_PATH)
    readme_md   = read(README_MD_PATH)

    output = f'''/**
 * src/shared/skill/templates.ts
 *
 * AUTO-GENERATED by scripts/build-skill-templates.py — do not edit by hand.
 * Edit the .md files in static/skill-template/ instead, then re-run the script.
 */

export const SKILL_MD: string = {json.dumps(skill_md)};

export const REPORT_PLAYBOOK_MD: string = {json.dumps(playbook_md)};

export const README_MD: string = {json.dumps(readme_md)};
'''

    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    with open(OUTPUT_PATH, 'w', encoding='utf-8') as f:
        f.write(output)

    print(f'✓ Wrote {OUTPUT_PATH} ({len(output)} bytes)')


if __name__ == '__main__':
    main()
